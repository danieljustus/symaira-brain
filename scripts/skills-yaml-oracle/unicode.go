package main

import (
	"fmt"
	"io"
	"unicode"
)

// Generate L/Nd membership from the effective pinned Go runtime, not host Rust.
func unicodeRanges(output io.Writer) error {
	if _, err := fmt.Fprintf(output, "// Generated by Go 1.26.7 skills-yaml-oracle -unicode (Unicode %s).\n// Exact unicode.IsLetter / unicode.IsDigit membership; do not edit.\n", unicode.Version); err != nil {
		return err
	}
	for _, category := range []struct {
		name     string
		contains func(rune) bool
	}{{"LETTER", unicode.IsLetter}, {"DIGIT", unicode.IsDigit}} {
		if _, err := fmt.Fprintf(output, "#[rustfmt::skip]\npub(super) const %s: &[(u32, u32)] = &[\n", category.name); err != nil {
			return err
		}
		count := 0
		for ch := rune(0); ch <= unicode.MaxRune; ch++ {
			if !category.contains(ch) {
				continue
			}
			start := ch
			for ch < unicode.MaxRune && category.contains(ch+1) {
				ch++
			}
			if count%6 == 0 {
				if _, err := fmt.Fprint(output, "    "); err != nil {
					return err
				}
			}
			if _, err := fmt.Fprintf(output, "(0x%x, 0x%x),", start, ch); err != nil {
				return err
			}
			count++
			if count%6 == 0 {
				if _, err := fmt.Fprintln(output); err != nil {
					return err
				}
			}
		}
		if count%6 != 0 {
			if _, err := fmt.Fprintln(output); err != nil {
				return err
			}
		}
		if _, err := fmt.Fprint(output, "];\n"); err != nil {
			return err
		}
		if category.name == "LETTER" {
			if _, err := fmt.Fprintln(output); err != nil {
				return err
			}
		}
	}
	return nil
}
