#!/usr/bin/env python3
"""Tests for manifests.py. The v0.12.0 fixture is the formula GoReleaser
published; the Rust render keeps its layout apart from the generator header."""

from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import manifests  # noqa: E402
import package  # noqa: E402

FIXTURES = HERE / "fixtures"
VERSION = "0.13.0-candidate.0123456789ab"


class Manifests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="rust-release-manifests-"))
        self.addCleanup(shutil.rmtree, self.tmp)

    def render(self, version: str, checksums: Path, *extra: str) -> str:
        out = self.tmp / "out"
        manifests.main(["--version", version, "--checksums", str(checksums), "--out", str(out), *extra])
        return (out / "symbrain.rb").read_text()

    def candidate_checksums(self) -> tuple[Path, dict[str, str]]:
        digests = {}
        lines = []
        for goos in ["darwin", "linux"]:
            for arch in ["amd64", "arm64"]:
                if goos == "darwin" and arch == "amd64":
                    continue
                name = f"symbrain_{VERSION}_{goos}_{arch}.tar.gz"
                digests[name] = hashlib.sha256(name.encode()).hexdigest()
                lines += [f"{digests[name]}  {name}", f"{'0' * 64}  {name}.sbom.json"]
        path = self.tmp / "checksums.txt"
        path.write_text("\n".join(lines) + "\n")
        return path, digests

    def test_layout_matches_the_published_v0_12_0_formula_minus_intel_mac(self):
        published = (FIXTURES / "v0.12.0-symbrain.rb").read_text()
        rendered = self.render("0.12.0", FIXTURES / "v0.12.0-checksums.txt")
        intel = published.index("    if Hardware::CPU.intel?\n")
        published = published[:intel] + published[published.index("    if Hardware::CPU.arm?\n", intel):]
        published = published.replace("# This file was generated by GoReleaser. DO NOT EDIT.",
                                      "# This file was generated by scripts/rust-release/manifests.py. DO NOT EDIT.")
        # The bundle adds the worker installs and checks on top of the published layout.
        bundle = re.compile(r'^ +bin\.install "(symbrowse|symoperate|symscope)"\n'
                            r'|^ +system "#\{bin\}/symbrowse".*\n'
                            r'|^ +if OS\.mac\?\n(?: +assert_predicate .*\n)+ +end\n'
                            r'|^  conflicts_with .*\n\n', re.M)
        stripped = bundle.sub("", rendered)
        self.assertNotEqual(stripped, rendered)
        self.assertEqual(stripped, published)

    def install_blocks(self, formula: str) -> dict[str, list[str]]:
        """Per archive name: the `bin.install` targets of its install block."""
        blocks = {}
        for match in re.finditer(r'url "[^"]*/(symbrain_[^"]+\.tar\.gz)"(.*?)\n    end\n', formula, re.S):
            blocks[match[1]] = re.findall(r'bin\.install "([^"]+)"', match[2])
        return blocks

    def test_rust_render_installs_every_bundled_binary_with_exact_urls_and_digests(self):
        checksums, digests = self.candidate_checksums()
        formula = self.render(VERSION, checksums)
        self.assertIn("generated by scripts/rust-release/manifests.py", formula)
        self.assertNotIn("symbrain-go", formula)
        for name, digest in digests.items():
            self.assertIn(f'url "{manifests.REPOSITORY}/releases/download/v{VERSION}/{name}"\n'
                          f'      sha256 "{digest}"', formula)
        self.assertNotIn("_darwin_amd64", formula)
        self.assertNotIn("_windows_", formula)
        blocks = self.install_blocks(formula)
        self.assertEqual(set(blocks), set(digests))
        for name, installed in blocks.items():
            if "_darwin_" in name:
                self.assertEqual(installed, ["symbrain", "symbrowse", "symoperate", "symscope"], name)
            else:
                self.assertEqual(installed, ["symbrain", "symbrowse"], name)

    def test_installed_binaries_match_what_the_archive_contract_ships(self):
        checksums, _ = self.candidate_checksums()
        for name, installed in self.install_blocks(self.render(VERSION, checksums)).items():
            goos = name.split("_")[2]
            self.assertEqual(sorted(installed), sorted(set(package.expected_members("symbrain", goos)) - set(package.DOCS)))

    def test_test_block_checks_symbrain_and_symbrowse_versions(self):
        checksums, _ = self.candidate_checksums()
        test_block = self.render(VERSION, checksums).split("  test do\n", 1)[1]
        self.assertIn('system "#{bin}/symbrain", "version"', test_block)
        self.assertIn('system "#{bin}/symbrowse", "version"', test_block)
        # darwin-only workers are asserted behind OS.mac? so the linux formula test stays valid
        self.assertRegex(test_block, r'if OS\.mac\?\n\s+assert_predicate bin/"symoperate", :executable\?\n'
                                     r'\s+assert_predicate bin/"symscope", :executable\?\n\s+end\n')

    def test_symbrowse_checksum_lines_do_not_reach_the_symbrain_formula(self):
        checksums, digests = self.candidate_checksums()
        lines = checksums.read_text().splitlines()
        for name in list(digests):
            browse = name.replace("symbrain_", "symbrowse_", 1)
            lines += [f"{hashlib.sha256(browse.encode()).hexdigest()}  {browse}", f"{'0' * 64}  {browse}.sbom.json"]
        with_browse = self.tmp / "with-browse-checksums.txt"
        with_browse.write_text("\n".join(lines) + "\n")
        formula = self.render(VERSION, with_browse)
        self.assertEqual(formula, self.render(VERSION, checksums))
        self.assertNotIn("symbrowse_", formula)  # the standalone archive is never a formula source

    def test_formula_conflicts_with_the_standalone_symbrowse_formula(self):
        checksums, _ = self.candidate_checksums()
        formula = self.render(VERSION, checksums)
        self.assertIn('  conflicts_with "danieljustus/tap/symbrowse", because: "both install the symbrowse binary"\n', formula)
        # declared on the formula level, between the platform blocks and the test block
        self.assertLess(formula.index("  on_linux do"), formula.index("  conflicts_with"))
        self.assertLess(formula.index("  conflicts_with"), formula.index("  test do"))

    def render_stub(self, version: str, checksums: Path) -> str:
        out = self.tmp / "out"
        manifests.main(["--version", version, "--checksums", str(checksums), "--out", str(out)])
        return (out / "symbrowse.rb").read_text()

    def test_symbrowse_stub_is_a_disabled_pointer_to_symbrain(self):
        checksums, _ = self.candidate_checksums()
        stub = self.render_stub(VERSION, checksums)
        self.assertIn("class Symbrowse < Formula\n", stub)
        self.assertRegex(stub, r'desc "[^"]+"')
        self.assertIn('homepage "https://github.com/danieljustus/symaira-browse"', stub)
        self.assertIn('license "Apache-2.0"', stub)
        self.assertRegex(stub, r'(?m)^  disable! date: "\d{4}-\d{2}-\d{2}", because: "[^"]*symbrain[^"]*"$')
        self.assertNotIn("deprecate!", stub)
        self.assertNotIn("conflicts_with", stub)
        self.assertNotIn(VERSION, stub)  # never points at the new bundle archive
        self.assertIn("generated by scripts/rust-release/manifests.py", stub)

    def test_symbrowse_stub_keeps_the_archived_go_artifacts_so_brew_can_still_load_it(self):
        checksums, _ = self.candidate_checksums()
        stub = self.render_stub(VERSION, checksums)
        urls = re.findall(r'url "([^"]+)"\n\s+sha256 "([0-9a-f]{64})"', stub)
        self.assertEqual(len(urls), 4)
        for url, _digest in urls:
            self.assertRegex(url, r"^https://github\.com/danieljustus/symaira-browse/releases/download/v0\.8\.0/symbrowse_0\.8\.0_(darwin|linux)_(amd64|arm64)\.tar\.gz$")

    def test_main_writes_both_formula_files_and_the_stub_is_independent_of_the_version(self):
        checksums, _ = self.candidate_checksums()
        first = self.render_stub(VERSION, checksums)
        self.assertTrue((self.tmp / "out" / "symbrain.rb").is_file())
        other = self.tmp / "other.txt"
        other.write_text("\n".join(f"{'1' * 64}  symbrain_9.9.9_{o}_{a}.tar.gz" for o, a in [("darwin", "arm64"), ("linux", "amd64"), ("linux", "arm64")]) + "\n")
        self.assertEqual(first, self.render_stub("9.9.9", other))

    @unittest.skipUnless(shutil.which("ruby"), "needs ruby")
    def test_both_rendered_files_are_valid_ruby(self):
        checksums, _ = self.candidate_checksums()
        self.render(VERSION, checksums)
        for name in ("symbrain.rb", "symbrowse.rb"):
            check = subprocess.run(["ruby", "-c", str(self.tmp / "out" / name)], capture_output=True, text=True)
            self.assertEqual(check.returncode, 0, f"{name}: {check.stderr}")

    def test_release_workflow_publishes_and_commits_both_formulae_together(self):
        workflow = (HERE.parents[1] / ".github/workflows/release.yml").read_text()
        for name in ("symbrain.rb", "symbrowse.rb"):
            self.assertIn(f'cp "$RUNNER_TEMP/manifests/{name}" "$tap/Formula/{name}"', workflow)
        self.assertIn("git add Formula/symbrain.rb Formula/symbrowse.rb\n", workflow)

    def test_only_the_release_workflow_writes_tap_formulae(self):
        for path in (HERE.parents[1] / ".github/workflows").glob("*.yml"):
            if path.name != "release.yml":
                self.assertNotIn("Formula/", path.read_text(), path.name)

    @unittest.skipUnless(shutil.which("ruby"), "needs ruby")
    def test_formula_is_valid_ruby(self):
        checksums, _ = self.candidate_checksums()
        self.render(VERSION, checksums)
        check = subprocess.run(["ruby", "-c", str(self.tmp / "out" / "symbrain.rb")], capture_output=True, text=True)
        self.assertEqual(check.returncode, 0, check.stderr)

    def test_missing_archive_malformed_line_and_v_prefix_are_rejected(self):
        checksums, _ = self.candidate_checksums()
        lines = [line for line in checksums.read_text().splitlines() if "linux_arm64.tar.gz " not in line + " "]
        partial = self.tmp / "partial.txt"
        partial.write_text("\n".join(lines) + "\n")
        with self.assertRaisesRegex(SystemExit, "lacks archives"):
            self.render(VERSION, partial)
        bad = self.tmp / "bad.txt"
        bad.write_text("not a checksum line\n")
        with self.assertRaisesRegex(SystemExit, "malformed"):
            self.render(VERSION, bad)
        with self.assertRaisesRegex(SystemExit, "invalid version"):
            self.render("v" + VERSION, checksums)


if __name__ == "__main__":
    unittest.main()
