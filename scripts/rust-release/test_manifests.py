#!/usr/bin/env python3
"""Tests for manifests.py. Fixtures are the published v0.12.0 checksums.txt
and the Formula/symbrain.rb GoReleaser pushed to danieljustus/homebrew-tap."""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import manifests  # noqa: E402

FIXTURES = HERE / "fixtures"
VERSION = "0.13.0-candidate.0123456789ab"


class Manifests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="rust-release-manifests-"))
        self.addCleanup(shutil.rmtree, self.tmp)

    def render(self, version: str, checksums: Path, *extra: str) -> tuple[str, dict]:
        out = self.tmp / "out"
        manifests.main(["--version", version, "--checksums", str(checksums), "--out", str(out), *extra])
        return (out / "symbrain.rb").read_text(), json.loads((out / "symbrain.json").read_text())

    def candidate_checksums(self) -> tuple[Path, dict[str, str]]:
        digests = {}
        lines = []
        for goos in ["darwin", "linux", "windows"]:
            for arch in ["amd64", "arm64"]:
                name = f"symbrain_{VERSION}_{goos}_{arch}." + ("zip" if goos == "windows" else "tar.gz")
                digests[name] = hashlib.sha256(name.encode()).hexdigest()
                lines += [f"{digests[name]}  {name}", f"{'0' * 64}  {name}.sbom.json"]
        path = self.tmp / "checksums.txt"
        path.write_text("\n".join(lines) + "\n")
        return path, digests

    def test_rollback_render_is_the_published_v0_12_0_formula(self):
        formula, scoop = self.render("0.12.0", FIXTURES / "v0.12.0-checksums.txt", "--legacy-go")
        self.assertEqual(formula, (FIXTURES / "v0.12.0-symbrain.rb").read_text())
        self.assertEqual(scoop["architecture"]["64bit"]["bin"], ["symbrain.exe"])
        self.assertEqual(scoop["architecture"]["64bit"]["hash"],
                         "3874802e4914194287fd63f2a3822015565274dc6f375116ac5bef109bf51f5e")

    def test_rust_render_installs_the_fallback_with_exact_urls_and_digests(self):
        checksums, digests = self.candidate_checksums()
        formula, scoop = self.render(VERSION, checksums)
        self.assertIn("generated by scripts/rust-release/manifests.py", formula)
        self.assertEqual(formula.count('bin.install "symbrain"\n'), 4)
        self.assertEqual(formula.count('bin.install "symbrain-go"\n'), 4)
        for name, digest in digests.items():
            if name.endswith(".tar.gz"):
                self.assertIn(f'url "{manifests.REPOSITORY}/releases/download/v{VERSION}/{name}"\n'
                              f'      sha256 "{digest}"', formula)
        self.assertEqual(set(scoop["architecture"]), {"64bit", "arm64"})
        for key, arch in [("64bit", "amd64"), ("arm64", "arm64")]:
            name = f"symbrain_{VERSION}_windows_{arch}.zip"
            entry = scoop["architecture"][key]
            self.assertEqual(entry["url"], f"{manifests.REPOSITORY}/releases/download/v{VERSION}/{name}")
            self.assertEqual((entry["hash"], entry["bin"]), (digests[name], ["symbrain.exe", "symbrain-go.exe"]))
        self.assertEqual((scoop["version"], scoop["license"]), (VERSION, "Apache-2.0"))

    @unittest.skipUnless(shutil.which("ruby"), "needs ruby")
    def test_formula_is_valid_ruby(self):
        checksums, _ = self.candidate_checksums()
        self.render(VERSION, checksums)
        check = subprocess.run(["ruby", "-c", str(self.tmp / "out" / "symbrain.rb")], capture_output=True, text=True)
        self.assertEqual(check.returncode, 0, check.stderr)

    def test_missing_archive_malformed_line_and_v_prefix_are_rejected(self):
        checksums, _ = self.candidate_checksums()
        lines = [line for line in checksums.read_text().splitlines() if "linux_arm64.tar.gz " not in line + " "]
        partial = self.tmp / "partial.txt"
        partial.write_text("\n".join(lines) + "\n")
        with self.assertRaisesRegex(SystemExit, "lacks archives"):
            self.render(VERSION, partial)
        bad = self.tmp / "bad.txt"
        bad.write_text("not a checksum line\n")
        with self.assertRaisesRegex(SystemExit, "malformed"):
            self.render(VERSION, bad)
        with self.assertRaisesRegex(SystemExit, "invalid version"):
            self.render("v" + VERSION, checksums)


if __name__ == "__main__":
    unittest.main()
