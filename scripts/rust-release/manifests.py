#!/usr/bin/env python3
"""Render the Homebrew formula and Scoop manifest from a release checksums.txt.

  manifests.py --version 0.13.0 --checksums dist/checksums.txt --out manifests
  manifests.py --version 0.12.0 --checksums checksums.txt --out rollback --legacy-go

Writes `symbrain.rb` (danieljustus/homebrew-tap, Formula/) and `symbrain.json`
(danieljustus/scoop-bucket, repository root). Nothing is published: the files
are review artifacts until the cutover (#782) pushes them.

Rust archives carry `symbrain` plus the `symbrain-go` fallback, and both are
installed so the fallback is on PATH. `--legacy-go` renders the Go-only v0.12.x
layout that GoReleaser published; that is the rollback path, and for v0.12.0 it
reproduces the published formula byte for byte.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPOSITORY = "https://github.com/danieljustus/symaira-brain"
DESCRIPTION = "Portable agent context with an MCP gateway for vault, memory, and skills"
VERSION = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$")
CHECKSUM_LINE = re.compile(r"^([0-9a-f]{64})  (\S+)$")


def read_checksums(path: Path, version: str) -> dict[tuple[str, str], str]:
    digests = {}
    for line in path.read_text(encoding="ascii").splitlines():
        match = CHECKSUM_LINE.fullmatch(line)
        if not match:
            raise SystemExit(f"malformed checksum line: {line!r}")
        digest, name = match.groups()
        archive = re.fullmatch(rf"symbrain_{re.escape(version)}_(darwin|linux|windows)_(amd64|arm64)\.(tar\.gz|zip)", name)
        if archive:
            digests[(archive[1], archive[2])] = digest
    missing = {(o, a) for o in ["darwin", "linux", "windows"] for a in ["amd64", "arm64"]} - set(digests)
    if missing:
        raise SystemExit(f"checksums.txt lacks archives for {sorted(missing)}")
    return digests


def formula(version: str, digests: dict[tuple[str, str], str], legacy_go: bool) -> str:
    header = ("# This file was generated by GoReleaser. DO NOT EDIT." if legacy_go
              else "# This file was generated by scripts/rust-release/manifests.py. DO NOT EDIT.")
    binaries = ["symbrain"] if legacy_go else ["symbrain", "symbrain-go"]
    install = "".join(f'        bin.install "{name}"\n' for name in binaries)

    def block(goos: str, arch: str, condition: str, blank: bool) -> str:
        name = f"symbrain_{version}_{goos}_{arch}.tar.gz"
        return (f"    if {condition}\n"
                f'      url "{REPOSITORY}/releases/download/v{version}/{name}"\n'
                f'      sha256 "{digests[(goos, arch)]}"\n'
                + ("\n" if blank else "")
                + "      define_method(:install) do\n" + install + "      end\n    end\n")

    # Layout follows the formula GoReleaser published for v0.12.x, so a
    # rollback render is byte-identical and a diff against it stays small.
    return ("# typed: false\n# frozen_string_literal: true\n\n" + header + "\n"
            "class Symbrain < Formula\n"
            f'  desc "{DESCRIPTION}"\n  homepage "{REPOSITORY}"\n  license "Apache-2.0"\n\n'
            "  on_macos do\n"
            + block("darwin", "amd64", "Hardware::CPU.intel?", True)
            + block("darwin", "arm64", "Hardware::CPU.arm?", True)
            + "  end\n\n  on_linux do\n"
            + block("linux", "amd64", "Hardware::CPU.intel? && Hardware::CPU.is_64_bit?", False)
            + block("linux", "arm64", "Hardware::CPU.arm? && Hardware::CPU.is_64_bit?", False)
            + "  end\n\n  test do\n"
            '    system "#{bin}/symbrain", "version"\n  end\nend\n')


def scoop(version: str, digests: dict[tuple[str, str], str], legacy_go: bool) -> str:
    binaries = ["symbrain.exe"] if legacy_go else ["symbrain.exe", "symbrain-go.exe"]
    architecture = {
        key: {"url": f"{REPOSITORY}/releases/download/v{version}/symbrain_{version}_windows_{arch}.zip",
              "bin": binaries, "hash": digests[("windows", arch)]}
        for key, arch in [("64bit", "amd64"), ("arm64", "arm64")]
    }
    manifest = {"version": version, "architecture": architecture, "homepage": REPOSITORY,
                "license": "Apache-2.0", "description": DESCRIPTION}
    return json.dumps(manifest, indent=4) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", required=True, help="release version without the v prefix")
    parser.add_argument("--checksums", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--legacy-go", action="store_true", help="Go-only v0.12.x archives (rollback)")
    args = parser.parse_args(argv)
    if not VERSION.fullmatch(args.version):
        raise SystemExit(f"invalid version {args.version!r} (no leading v)")
    digests = read_checksums(args.checksums, args.version)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "symbrain.rb").write_text(formula(args.version, digests, args.legacy_go), encoding="utf-8")
    (args.out / "symbrain.json").write_text(scoop(args.version, digests, args.legacy_go), encoding="utf-8")
    print(args.out / "symbrain.rb", args.out / "symbrain.json")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
