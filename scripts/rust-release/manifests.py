#!/usr/bin/env python3
"""Render the Homebrew formula from a release checksums.txt.

  manifests.py --version 0.13.0 --checksums dist/checksums.txt --out manifests

Writes `symbrain.rb` and `symbrowse.rb` (danieljustus/homebrew-tap, Formula/).
`symbrowse.rb` is a disabled stub: the standalone formula installed the same
`bin/symbrowse` that the symbrain formula now installs, so symbrain declares a
conflict with it and the stub tells remaining users to install symbrain. The symbrain archive
is the release bundle: `symbrain` and `symbrowse` everywhere, plus `symoperate`
and `symscope` on macOS (package.BUNDLED_WORKERS); the formula installs every
binary the archive of that platform holds. There is no Go fallback and no Go
rollback. The standalone symbrowse archive is never a formula source.
The layout follows the formula GoReleaser published for v0.12.x so a diff
against the tap history stays small.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import package  # noqa: E402

REPOSITORY = "https://github.com/danieljustus/symaira-brain"
DESCRIPTION = "Portable agent context with an MCP gateway for vault, memory, and skills"
VERSION = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$")
CHECKSUM_LINE = re.compile(r"^([0-9a-f]{64})  (\S+)$")
PLATFORMS = {("darwin", "arm64"), ("linux", "amd64"), ("linux", "arm64")}

STUB_DISABLE_DATE = "2026-11-18"
STUB_DESCRIPTION = "Agent-operable browser automation over Chrome DevTools Protocol"
STUB_HOMEPAGE = "https://github.com/danieljustus/symaira-browse"
STUB_REASON = "bundled with symbrain since the built-in worker release; run `brew install danieljustus/tap/symbrain`"
# The archived Go v0.8.0 artifacts the standalone formula always pointed at. A
# disabled formula keeps them (like the other disabled stubs in the tap) so
# Homebrew can still load and describe it; it can never be installed.
LEGACY_URL = f"{STUB_HOMEPAGE}/releases/download/v0.8.0/symbrowse_0.8.0_%s_%s.tar.gz"
LEGACY_ARCHIVES = {
    ("darwin", "amd64"): "2606f1779ce671b93e64e6d70e2a821aad26f1ec8f48e80f22959466a8efd7da",
    ("darwin", "arm64"): "ce682ff06e2f9e74c02a5662498f04580065554ab67822a65a786e15b487c36b",
    ("linux", "amd64"): "580037291caab834738d28db8b803adf3d92b9bebfee937ce9c9055e888e5aa1",
    ("linux", "arm64"): "725e7d0ee18cc67a715f540ea5cbe25d17d7e0a9351158b8a8ec084d10165c62",
}


def read_checksums(path: Path, version: str) -> dict[tuple[str, str], str]:
    digests = {}
    for line in path.read_text(encoding="ascii").splitlines():
        match = CHECKSUM_LINE.fullmatch(line)
        if not match:
            raise SystemExit(f"malformed checksum line: {line!r}")
        digest, name = match.groups()
        archive = re.fullmatch(rf"symbrain_{re.escape(version)}_(darwin|linux)_(amd64|arm64)\.tar\.gz", name)
        if archive:
            digests[(archive[1], archive[2])] = digest
    missing = PLATFORMS - set(digests)
    if missing:
        raise SystemExit(f"checksums.txt lacks archives for {sorted(missing)}")
    return digests


def formula(version: str, digests: dict[tuple[str, str], str]) -> str:
    def block(goos: str, arch: str, condition: str, blank: bool) -> str:
        name = f"symbrain_{version}_{goos}_{arch}.tar.gz"
        return (f"    if {condition}\n"
                f'      url "{REPOSITORY}/releases/download/v{version}/{name}"\n'
                f'      sha256 "{digests[(goos, arch)]}"\n'
                + ("\n" if blank else "")
                + "      define_method(:install) do\n"
                + "".join(f'        bin.install "{binary}"\n' for binary in ["symbrain", *package.BUNDLED_WORKERS[goos]])
                + "      end\n    end\n")

    return ("# typed: false\n# frozen_string_literal: true\n\n"
            "# This file was generated by scripts/rust-release/manifests.py. DO NOT EDIT.\n"
            "class Symbrain < Formula\n"
            f'  desc "{DESCRIPTION}"\n  homepage "{REPOSITORY}"\n  license "Apache-2.0"\n\n'
            "  on_macos do\n"
            + block("darwin", "arm64", "Hardware::CPU.arm?", True)
            + "  end\n\n  on_linux do\n"
            + block("linux", "amd64", "Hardware::CPU.intel? && Hardware::CPU.is_64_bit?", False)
            + block("linux", "arm64", "Hardware::CPU.arm? && Hardware::CPU.is_64_bit?", False)
            + "  end\n\n"
            '  conflicts_with "danieljustus/tap/symbrowse", because: "both install the symbrowse binary"\n\n'
            "  test do\n"
            '    system "#{bin}/symbrain", "version"\n'
            '    system "#{bin}/symbrowse", "version"\n'
            "    if OS.mac?\n"
            '      assert_predicate bin/"symoperate", :executable?\n'
            '      assert_predicate bin/"symscope", :executable?\n'
            "    end\n  end\nend\n")


def symbrowse_stub() -> str:
    """Disabled `symbrowse` formula: same class name and metadata, never installable."""
    def entry(goos: str, arch: str, condition: str) -> str:
        return (f"    if {condition}\n"
                f'      url "{LEGACY_URL % (goos, arch)}"\n'
                f'      sha256 "{LEGACY_ARCHIVES[(goos, arch)]}"\n\n'
                "      define_method(:install) do\n"
                '        bin.install "symbrowse"\n'
                "      end\n    end\n")

    return ("# typed: false\n# frozen_string_literal: true\n\n"
            "# This file was generated by scripts/rust-release/manifests.py. DO NOT EDIT.\n"
            "class Symbrowse < Formula\n"
            f'  desc "{STUB_DESCRIPTION}"\n  homepage "{STUB_HOMEPAGE}"\n  license "Apache-2.0"\n\n'
            f'  disable! date: "{STUB_DISABLE_DATE}", because: "{STUB_REASON}"\n\n'
            "  on_macos do\n"
            + entry("darwin", "amd64", "Hardware::CPU.intel?")
            + entry("darwin", "arm64", "Hardware::CPU.arm?")
            + "  end\n\n  on_linux do\n"
            + entry("linux", "amd64", "Hardware::CPU.intel? && Hardware::CPU.is_64_bit?")
            + entry("linux", "arm64", "Hardware::CPU.arm? && Hardware::CPU.is_64_bit?")
            + "  end\n\n  test do\n"
            '    system "#{bin}/symbrowse", "version"\n'
            "  end\nend\n")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", required=True, help="release version without the v prefix")
    parser.add_argument("--checksums", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    if not VERSION.fullmatch(args.version):
        raise SystemExit(f"invalid version {args.version!r} (no leading v)")
    digests = read_checksums(args.checksums, args.version)
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in (("symbrain.rb", formula(args.version, digests)), ("symbrowse.rb", symbrowse_stub())):
        (args.out / name).write_text(text, encoding="utf-8")
        print(args.out / name)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
