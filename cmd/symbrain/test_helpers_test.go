package main

import (
	"bytes"
	"sync"
)

// lockedBuffer makes concurrent diagnostic writes and reads safe in tests that
// run a command in one goroutine while inspecting its stderr in another.
type lockedBuffer struct {
	mu  sync.Mutex
	buf bytes.Buffer
}

func (b *lockedBuffer) Write(p []byte) (int, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.buf.Write(p)
}

func (b *lockedBuffer) String() string {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.buf.String()
}
